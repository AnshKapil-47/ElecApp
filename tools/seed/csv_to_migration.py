#!/usr/bin/env python3
"""Turn election_type_field_seed.csv into a Flyway migration that (re)loads election_type_field.

Usage:
  python3 tools/seed/csv_to_migration.py docs/data-model/election_type_field_seed.csv \
      backend/src/main/resources/db/migration/V3__seed_election_type_field.sql

For a later change of the sheet, write a NEW version (V7__reseed_election_type_field.sql, ...);
never edit an applied migration. The generated SQL replaces all rows in one transaction.
"""
import csv
import sys

TYPES = ["LOK_SABHA", "VIDHAN_SABHA", "NAGAR_NIGAM", "NAGAR_PALIKA",
         "NAGAR_PARISHAD", "ZILLA_PANCHAYAT", "PANCHAYAT_SAMITI", "PANCHAYAT"]


def q(v):
    if v is None or v == "":
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def main(src, out):
    with open(src, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    need = {"election_type_code", "source_column", "value_type", "label_en", "label_mt",
            "usage", "filter_order", "display_order", "on_slip"}
    missing = need - set(rows[0])
    if missing:
        sys.exit(f"CSV is missing columns: {sorted(missing)}")
    bad = {r["election_type_code"] for r in rows} - set(TYPES)
    if bad:
        sys.exit(f"Unknown election types: {sorted(bad)}")

    lines = [
        "-- Generated by tools/seed/csv_to_migration.py from docs/data-model/election_type_field_seed.csv",
        "-- Source of truth: docs/data-model/NEW_APP_COLUMN_DETAILS.xlsx (skin = FILTER, green = DISPLAY).",
        "-- Do not edit by hand. Regenerate into a new V<n> file when the sheet changes.",
        "DELETE FROM election_type_field;",
        "INSERT INTO election_type_field (election_type_id, source_column, value_type, label_en, label_mt,",
        "                                 usage, filter_order, display_order, on_slip)",
        "SELECT et.id, v.source_column, v.value_type, v.label_en, v.label_mt, v.usage,",
        "       v.filter_order::smallint, v.display_order::smallint, v.on_slip::boolean",
        "FROM (VALUES",
    ]
    vals = []
    for r in rows:
        vals.append("  ({}, {}, {}, {}, {}, {}, {}, {}, {})".format(
            q(r["election_type_code"]), q(r["source_column"]), q(r["value_type"]), q(r["label_en"]),
            q(r["label_mt"]), q(r["usage"]), q(r["filter_order"]), q(r["display_order"]),
            q(r["on_slip"])))
    lines.append(",\n".join(vals))
    lines += [
        ") AS v(code, source_column, value_type, label_en, label_mt, usage, filter_order, display_order, on_slip)",
        "JOIN election_type et ON et.code = v.code;",
        "",
        "-- Safety checks: every type has its FILTER fields, and its booth column is displayed.",
        "DO $$ BEGIN",
        "  IF EXISTS (SELECT 1 FROM election_type et WHERE NOT EXISTS (",
        "      SELECT 1 FROM election_type_field f WHERE f.election_type_id = et.id AND f.usage = 'FILTER'))",
        "  THEN RAISE EXCEPTION 'an election type has no FILTER fields'; END IF;",
        "  IF EXISTS (SELECT 1 FROM election_type et WHERE NOT EXISTS (",
        "      SELECT 1 FROM election_type_field f WHERE f.election_type_id = et.id AND f.source_column = et.booth_column))",
        "  THEN RAISE EXCEPTION 'an election type does not display its booth column'; END IF;",
        "END $$;",
        "",
    ]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}: {len(rows)} rows")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
